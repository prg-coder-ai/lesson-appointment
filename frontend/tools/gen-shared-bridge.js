#!/usr/bin/env node
'use strict';
/*
 * 生成「共享领域层 → 浏览器全局」桥接产物。
 *
 * 输入：shared/domain/{term,refundRule,bookingState,appointmentState,mask,datetime,errorCode}.js
 *       + shared/constants.js（bookingState 依赖其中的 BOOKING_STATUS，须一并内联）
 *       + shared/adapters/{net,storage,ui,router}.js（平台适配层，运行时自动探测 wx/Web）
 *       （均为 ESM、零 DOM、零运行时 API 依赖）
 * 产出：frontend/js/shared-domain-bridge.js（经典脚本，非模块）
 *       把领域层纯函数挂到 window.*Domain，把适配层挂到 window.{Net,Storage,Ui,Router}Adapter，
 *       供 frontend 下 classic <script> 委托调用
 *       （dev 与 dist 两路都覆盖：build.js 的 buildJs() 会把它 minify 进 dist/js/，
 *        dev 代理直接读 frontend/ 源码；源码 HTML 已含本脚本标签，故 dev 亦可用）。
 *
 * 注意：本文件是「机械转译」，只剥离 ESM 关键字，不改写任何逻辑——
 *       领域层算法以 shared/domain 为唯一权威源，改算法只改那边。
 *       跨文件 import（如 bookingState 的 import { BOOKING_STATUS } from '../constants.js'）
 *       由本生成器通过内联 constants.js 源文本解决，剥离 import 行后常量仍在作用域内。
 */
const fs = require('fs');
const path = require('path');

const FRONTEND_DIR = path.resolve(__dirname, '..');            // frontend/
const SHARED_ROOT = path.resolve(FRONTEND_DIR, '..', 'shared');        // repo/shared
const SHARED_DOMAIN = path.join(SHARED_ROOT, 'domain');                // repo/shared/domain
const SHARED_ADAPTERS = path.join(SHARED_ROOT, 'adapters');            // repo/shared/adapters
const OUT = path.join(FRONTEND_DIR, 'js', 'shared-domain-bridge.js');

// 机械剥离 ESM：去掉 import 行 + 行首 export 关键字（保留 const/function 声明）。
function stripEsm(code) {
  code = code.replace(/^[ \t]*import\s+.*?;?\s*$/gm, '');
  code = code.replace(/^[ \t]*export\s+default\s+[^\n]*$/gm, ''); // 去掉 default export 整行（适配器用）
  code = code.replace(/^[ \t]*export\s+/gm, '');
  return code;
}

// 依次拼接：constants 先（bookingState 依赖） → 各 domain 文件
const DOMAIN_FILES = [
  'term.js',
  'refundRule.js',
  'bookingState.js',
  'appointmentState.js',
  'mask.js',
  'datetime.js',
  'errorCode.js'
];

const ADAPTER_FILES = [
  'net.js',
  'storage.js',
  'ui.js',
  'router.js'
];

function readStripped(relPath) {
  return stripEsm(fs.readFileSync(path.join(SHARED_ROOT, relPath), 'utf8')) + '\n';
}

function generateSharedBridge() {
  const constSrc = readStripped('constants.js');
  let domainSrc = '';
  for (const f of DOMAIN_FILES) {
    domainSrc += readStripped(path.join('domain', f));
  }
  let adapterSrc = '';
  for (const f of ADAPTER_FILES) {
    adapterSrc += readStripped(path.join('adapters', f));
  }

  const header = `/* AUTO-GENERATED by frontend/tools/gen-shared-bridge.js — DO NOT EDIT BY HAND.
 * 源：../shared/{constants.js,domain/*,adapters/{net,storage,ui,router}.js}
 *     （ESM 领域层 + 平台适配层，唯一权威源）。
 * 本文件仅把纯函数/适配对象挂到 window.*Domain / window.*Adapter，供 classic 脚本委托。
 * 改算法请改 shared/，再重跑本生成器（build.js 已自动调用）。
 */
`;

  const body = `
window.TermDomain = {
  TERM_DICT: TERM_DICT,
  TERM_KEYS: TERM_KEYS,
  PROTECTED_WORDS: PROTECTED_WORDS,
  COURSE_TYPE_OPTIONS: COURSE_TYPE_OPTIONS,
  getTerms: getTerms,
  termText: termText,
  getOptions: getOptions,
  normalizeCourseType: normalizeCourseType,
  courseTypeText: courseTypeText,
  enumTermText: enumTermText
};
window.RefundRuleDomain = {
  REFUND_BUILT_IN_FALLBACK: REFUND_BUILT_IN_FALLBACK,
  formatRefundMinutes: formatRefundMinutes,
  refundRuleToMinutes: refundRuleToMinutes,
  refundRuleFromMinutes: refundRuleFromMinutes,
  refundRuleZoneText: refundRuleZoneText,
  validateRefundRule: validateRefundRule,
  resolveEffectiveRule: resolveEffectiveRule,
  evaluateRefund: evaluateRefund
};
window.BookingStateDomain = {
  BOOKING_STATUS_ALL: BOOKING_STATUS_ALL,
  NON_OCCUPYING_STATUSES: NON_OCCUPYING_STATUSES,
  normalizeBookingStatus: normalizeBookingStatus,
  bookingOccupiesSeat: bookingOccupiesSeat,
  isNonOccupying: isNonOccupying,
  isWaiting: isWaiting,
  isBooked: isBooked,
  isPending: isPending,
  isCancelled: isCancelled,
  isCompleted: isCompleted,
  canConfirm: canConfirm,
  canCancel: canCancel,
  canReject: canReject,
  bookingStatusText: bookingStatusText,
  FULLY_BOOKED_TEXT: FULLY_BOOKED_TEXT,
  formatRemainingSites: formatRemainingSites,
  isSiteFull: isSiteFull
};
window.AppointmentStateDomain = {
  APPOINTMENT_STATUS: APPOINTMENT_STATUS,
  APPOINTMENT_CLOSED_STATUSES: APPOINTMENT_CLOSED_STATUSES,
  appointmentStatusText: appointmentStatusText,
  isAppointmentClosed: isAppointmentClosed
};
window.MaskDomain = {
  maskPhone: maskPhone,
  maskEmail: maskEmail
};
window.DatetimeDomain = {
  formatDateTime: formatDateTime,
  formatDate: formatDate,
  parseLocalDate: parseLocalDate,
  parseLocalDateTime: parseLocalDateTime,
  weekdayCN: weekdayCN,
  toDateTimeLocalValue: toDateTimeLocalValue
};
window.ErrorCodeDomain = {
  RESULT_OK: RESULT_OK,
  resolveResult: resolveResult,
  resolveRequestError: resolveRequestError,
  errorMessage: errorMessage
};

/* ---- 平台适配层（shared/adapters/*，零 DOM，运行时自动探测 wx/Web） ---- */
window.NetAdapter = {
  transport: transport
};
window.StorageAdapter = {
  storage: storage
};
window.UiAdapter = {
  alert: alert,
  confirm: confirm,
  prompt: prompt,
  setPromptResolver: setPromptResolver
};
window.RouterAdapter = {
  setRoutes: setRoutes,
  to: to,
  replace: replace,
  back: back,
  current: current,
  parseQuery: parseQuery,
  openUrl: openUrl
};
`;

  fs.writeFileSync(OUT, header + constSrc + domainSrc + adapterSrc + body, 'utf8');
  console.log('  shared-domain-bridge.js generated ->', OUT);
}

module.exports = { generateSharedBridge, stripEsm };

// 直接 node 调用时也执行
if (require.main === module) generateSharedBridge();
