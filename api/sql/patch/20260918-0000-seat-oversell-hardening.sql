-- 库：lesson_appointment
-- 背景：并发闸门（BookingSeatService，2026-09-11 提交 857a233 引入）已覆盖 5 条
--       占位写路径（create / update 改订 / updateStatus 状态回置 / promoteWaitlist 递补 /
--       asgn_student 指定学生），但 DB 层没有任何兜底约束。应用层一旦被绕过
--       （新增写路径、运维脚本、多实例版本不一致），DB 不会拦。
-- 幂等：重复执行会报 Duplicate key name / Duplicate check constraint name，可忽略。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 执行前自检（下面两条必须分别返回空结果 / 0，否则不要执行 1) 和 2)）
-- ---------------------------------------------------------------------------
-- 自检 1：同一 (排期, 学生) 是否已有重复行——有重复则唯一索引加不上
--   SELECT schedule_id, student_id, COUNT(*) c FROM booking
--   GROUP BY schedule_id, student_id HAVING c > 1;
--
-- 自检 2：是否存在负席位——有负数则 CHECK 约束加不上
--   SELECT COUNT(*) FROM course_schedule WHERE available_sites < 0;

-- ---------------------------------------------------------------------------
-- 1) 同一学生同一排期只允许一条预订记录
--    应用层已按「复用同一行」实现（BookingService.create / CourseScheduleService.asgn_student
--    查到已有记录就 UPDATE 而不再 INSERT），此索引是第二道防线：并发重复提交
--    在应用层漏掉时，DB 直接拒绝插入，不会出现同一学生吃两个席位。
--
--    语义边界：本索引禁止的是「同一 (排期, 学生) 存在两行」，不影响「取消后重新预约」——
--    那条路径复用同一行（UPDATE），不产生新行。若将来改为「保留多条历史记录」的设计，
--    需要先删掉这个索引。
-- ---------------------------------------------------------------------------
ALTER TABLE booking
  ADD UNIQUE KEY uk_booking_schedule_student (schedule_id, student_id);

-- ---------------------------------------------------------------------------
-- 2) 席位总数不得为负
--    available_sites 是 tinyint（范围 -128~127，允许负值）。原先的增量调整
--    `SET available_sites = available_sites + inc` 无下界，可一路减到负数：
--    该排期会永久拒绝新预定（闸门里 totalSites <= 0 直接抛异常），
--    而已占位数恒大于容量，等于长期挂着一条超卖记录。
--    应用层已加 assertSitesNotBelowOccupied（校验不得低于已占位数），
--    这里再加一道纯 DB 防线。
--    附注：tinyint 上限 127，若将来要开设超过 127 人的大班课，需先改为 smallint。
-- ---------------------------------------------------------------------------
ALTER TABLE course_schedule
  ADD CONSTRAINT course_schedule_chk_sites CHECK (available_sites >= 0);

-- ---------------------------------------------------------------------------
-- 3) 修正误导性列注释
--    该列语义是「可预约席位总数」，剩余 = 该值 - 占位预订数。
--    原注释写的是「剩余席位」，与代码里的用法相反（闸门按 `occupied >= totalSites` 判定满员），
--    后人若照注释理解，很容易把「剩余」当口径改出 bug。
-- ---------------------------------------------------------------------------
ALTER TABLE course_schedule
  MODIFY COLUMN available_sites tinyint(1) NOT NULL DEFAULT '1'
  COMMENT '可预约席位总数（非剩余席位；剩余 = 该值 - 占位预订数）';

